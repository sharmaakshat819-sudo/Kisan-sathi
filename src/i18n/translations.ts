export function getCropName(crop: { name: string; hindiName: string; marathiName: string; punjabiName: string; gujaratiName: string; teluguName: string }, lang: Language): string {
  switch (lang) {
    case 'hi':
      return crop.hindiName || crop.name;
    case 'mr':
      return crop.marathiName || crop.name;
    case 'pa':
      return crop.punjabiName || crop.name;
    case 'gu':
      return crop.gujaratiName || crop.name;
    case 'te':
      return crop.teluguName || crop.name;
    default:
      return crop.name;
  }
}
